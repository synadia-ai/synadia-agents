async def test_verify_live_outcomes(alice: NkeySigner, bob: NkeySigner, alice_id: AgentId) -> None:
    h = await _signed(alice, alice_id, name="n")
    ok = verify_sender_header(h, SUBJECT, PAYLOAD, mode="live")
    assert isinstance(ok, VerifiedSender)
    assert ok.id == alice_id and ok.name == "n" and ok.header is h
    assert await ok.resolve() is None  # unbound resolver
    assert str(ok) == f"{alice_id} (verified user, claimed account)"

    def rejected(
        header: AgentSenderHeader, arrival: str = SUBJECT, payload: bytes = PAYLOAD, **o: Any
    ) -> str:
        with pytest.raises(SenderVerificationError) as exc_info:
            verify_sender_header(header, arrival, payload, mode="live", **o)
        assert exc_info.value.code == 401
        assert exc_info.value.description == "sender rejected"
        return exc_info.value.detail

    assert "arrival subject" in rejected(h, "agents.prompt.demo.alice.other")
    assert "does not verify" in rejected(h, SUBJECT, b'{"prompt":"ho"}')
    stale = await _signed(alice, alice_id, ts=format_sender_timestamp(time.time() - 120))
    assert "window" in rejected(stale)
    future = await _signed(alice, alice_id, ts=format_sender_timestamp(time.time() + 29))
    assert isinstance(verify_sender_header(future, SUBJECT, PAYLOAD, mode="live"), VerifiedSender)
    replay_detail = rejected(h, nonce_seen=lambda _u, _n: True)
    assert "already seen" in replay_detail
    assert h.nonce is not None and h.nonce not in replay_detail
    # Rewritten fields: the parsed header still verifies the *signature* against its own fields,
    # so a rewritten `account`/`user` fails the ed25519 check.
    parsed = parse_sender_header(_with(h, account="ACME"))
    assert parsed is not None and "does not verify" in rejected(parsed)
    parsed = parse_sender_header(_with(h, user=bob.public_key))
    assert parsed is not None and "does not verify" in rejected(parsed)
    # `name` is outside the signature: a mutated name still verifies.
    parsed = parse_sender_header(_with(h, name="relay-rewrote-me"))
    assert parsed is not None
    assert isinstance(verify_sender_header(parsed, SUBJECT, PAYLOAD, mode="live"), VerifiedSender)
    # Stored mode: no freshness, no nonce lookup.
    assert isinstance(
        verify_sender_header(
            stale, SUBJECT, PAYLOAD, mode="stored", nonce_seen=lambda _u, _n: True
        ),
        VerifiedSender,
    )
    # A custom replay window and clock.
    assert "window" in rejected(h, replay_window_s=1.0, now=time.time() + 5)


