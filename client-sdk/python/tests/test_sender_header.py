# --- size bound ------------------------------------------------------------


async def test_bound_dominates_exact_size_for_every_shape(
    alice: NkeySigner, alice_id: AgentId
) -> None:
    for name in (None, "x", "n" * NAME_CAP, "Bob · 日本語 🤖"):
        for sub in ("a", SUBJECT, "svc.APP.prompt." + "t" * 40):
            h = await _signed(alice, alice_id, sub=sub, name=name)
            exact = encoded_header_length(serialize_sender_header(h))
            assert exact == expected_sender_header_bytes(
                id=alice_id, sub=sub, signed=True, name=name
            )
            assert exact <= max_sender_header_bytes(sub, name)
            claim = encoded_header_length(
                serialize_sender_header(build_claim_header(id=alice_id, name=name))
            )
            assert claim == expected_sender_header_bytes(
                id=alice_id, sub=sub, signed=False, name=name
            )
            assert claim <= max_sender_header_bytes(sub, name)


