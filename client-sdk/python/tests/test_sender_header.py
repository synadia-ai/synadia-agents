def test_vector_file_shape() -> None:
    assert VECTORS["header_framing_bytes"] == SENDER_HEADER_FRAMING_BYTES
    vectors = VECTORS["vectors"]
    assert len(vectors) >= MIN_VECTORS
    assert any(v["input"]["payload_b64"] == "" for v in vectors)
    assert any(not v["input"]["signed"] for v in vectors)
    assert any(not v["input"].get("name", "").isascii() for v in vectors)
    assert any("sub" in v["input"] for v in vectors)


@pytest.mark.parametrize("v", VECTORS["vectors"], ids=[v["id"] for v in VECTORS["vectors"]])
async def test_vector(v: dict[str, Any]) -> None:
    inp, exp = v["input"], v["expected"]
    signer = signer_from_seed(inp["seed"])
    assert signer.public_key == inp["user"]
    id = AgentId.new(inp["account"], inp["user"])
    payload = base64.b64decode(inp["payload_b64"])
    sub = inp.get("sub", inp["subject"])
    name = inp.get("name")

    if inp["signed"]:
        header = await sign_sender_header(
            signer=signer,
            id=id,
            sub=sub,
            payload=payload,
            name=name,
            ts=inp["ts"],
            nonce=inp["nonce"],
        )
    else:
        header = build_claim_header(id=id, name=name)

    value = serialize_sender_header(header)
    assert value == exp["header"]
    assert len(value.encode("utf-8")) == exp["header_bytes"]
    assert encoded_header_length(value) == exp["header_wire_bytes"]
    assert exp["header_wire_bytes"] == exp["header_bytes"] + SENDER_HEADER_FRAMING_BYTES
    assert encoded_header_length(value) <= max_sender_header_bytes(sub, name)

    parsed = parse_sender_header(exp["header"])
    assert parsed == header

    if inp["signed"]:
        data = build_signed_input(
            account=inp["account"],
            user=inp["user"],
            subject=sub,
            ts=inp["ts"],
            nonce=inp["nonce"],
            payload_sha256_hex=sha256_hex(payload),
        )
        assert data.decode("utf-8") == exp["signed_input"]
        assert header.sig == exp["sig"]
        assert verify_with_public_key(
            inp["user"], data, base64.urlsafe_b64decode(exp["sig"] + "==")
        )
        assert parsed is not None
        # Stored-mode verification against the signed subject (ts is fixed in the past).
        verified = verify_sender_header(parsed, sub, payload, mode="stored")
        assert isinstance(verified, VerifiedSender)
        assert verified.id == id
        assert verified.name == name
        assert verified.account_attested is False
        # Exact size accounting matches the vector for a NUID-length nonce.
        if len(inp["nonce"]) == NUID_LENGTH:
            assert (
                expected_sender_header_bytes(id=id, sub=sub, signed=True, name=name)
                == (exp["header_wire_bytes"])
            )
    else:
        assert "signed_input" not in exp
        assert parsed is not None
        claimed = verify_sender_header(parsed, sub, payload, mode="live")
        assert isinstance(claimed, ClaimedSender)
        assert not hasattr(claimed, "id")
        assert (
            expected_sender_header_bytes(id=id, sub=sub, signed=False, name=name)
            == (exp["header_wire_bytes"])
        )


