def test_subject_acceptance_equality_and_token_removal() -> None:
    ok = check_subject_acceptance
    assert ok(account="APP", sub="a.b", arrival_subject="a.b", account_token_position=None) is None
    assert ok(account="APP", sub="a.b", arrival_subject="a.c", account_token_position=None)
    # Token inserted at position 2: `svc.prompt` published, `svc.APP.prompt` arrives.
    assert (
        ok(
            account="APP",
            sub="svc.prompt",
            arrival_subject="svc.APP.prompt",
            account_token_position=2,
        )
        is None
    )
    assert (
        ok(
            account="APP",
            sub="svc.APP.prompt",
            arrival_subject="svc.APP.prompt",
            account_token_position=2,
        )
        is None
    )
    assert "not the header account" in (
        ok(
            account="EVIL",
            sub="svc.prompt",
            arrival_subject="svc.APP.prompt",
            account_token_position=2,
        )
        or ""
    )
    assert "beyond" in (
        ok(
            account="APP",
            sub="svc.prompt",
            arrival_subject="svc.APP.prompt",
            account_token_position=5,
        )
        or ""
    )
    assert "neither" in (
        ok(
            account="APP",
            sub="other.prompt",
            arrival_subject="svc.APP.prompt",
            account_token_position=2,
        )
        or ""
    )
    assert normalize_account_token_position(None) is None
    assert normalize_account_token_position(1) == 1
    for bad in (0, -1, 1.5, True, "2"):
        with pytest.raises(IdentityError, match="1-based"):
            normalize_account_token_position(bad)  # type: ignore[arg-type]


