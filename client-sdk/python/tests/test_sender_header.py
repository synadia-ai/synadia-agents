# --- name validation -------------------------------------------------------


def test_name_rules_count_utf16_units_and_reject_controls() -> None:
    assert_valid_sender_name("x" * NAME_CAP)
    assert_valid_sender_name("Bob · 日本語")
    with pytest.raises(IdentityError, match="64 UTF-16 code units"):
        assert_valid_sender_name("x" * (NAME_CAP + 1))
    with pytest.raises(IdentityError, match="64 UTF-16 code units"):
        assert_valid_sender_name("🤖" * (NAME_CAP // 2 + 1))  # an emoji counts 2
    assert_valid_sender_name("🤖" * (NAME_CAP // 2))
    for bad in ("a\nb", "a\tb", f"a{C1_NEL}b", "a\x7fb", f"a{LINE_SEP}b"):
        with pytest.raises(IdentityError, match="control character"):
            assert_valid_sender_name(bad)
    with pytest.raises(IdentityError, match="lone surrogate"):
        assert_valid_sender_name("a\ud800b")
    # The message never echoes the name.
    try:
        assert_valid_sender_name("secret\n")
    except IdentityError as exc:
        assert "secret" not in str(exc)


