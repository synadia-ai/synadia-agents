async def _signed(alice: NkeySigner, alice_id: AgentId, **overrides: Any) -> AgentSenderHeader:
    kwargs: dict[str, Any] = {"signer": alice, "id": alice_id, "sub": SUBJECT, "payload": PAYLOAD}
    kwargs.update(overrides)
    return await sign_sender_header(**kwargs)


def _with(h: AgentSenderHeader, **patch: Any) -> str:
    o = json.loads(serialize_sender_header(h))
    for k, v in patch.items():
        if v is None:
            o.pop(k, None)
        else:
            o[k] = v
    return json.dumps(o, separators=(",", ":"), ensure_ascii=False)


